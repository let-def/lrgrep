(* The logic:
   - Tree-sitter do not expect an explicit "EOF" symbol, we strip them from the
     original grammar
   - Rules involving `error` symbol are likely noise too, we ignore them
   - Tree-sitter do not support ϵ-rules -> rewrite grammar
   - Conflicts are specified with a slightly different formalism ->
     reverse-engineer conflict resolution from the generated automaton

   The flow:
   - analyze the grammar:
     - find which productions to import
     - find which derive non-null string (for rewriting of ϵ-rules and nts)
   - from the analysis, we can directly generate a tree-sitter template
   - but we don't stop here:
     - transform the conflicts in the automaton into a set of
       constraints
     - solve the constraints
     - inject the solution in the grammar prior to generation

   Constraints are solved as follow:
   - tree-sitter sets a precedence value at the level of productions
   - for each item, we will generate a variable representing its precedence level
   - the equations are all of the form `var ≥_{Left,Right,Prec} var`, so we can
     compute the SCC of the graph generated by these relations to rank them
   - however doing this naively introduce too many precedence levels and do not
     support associativity out of the box
   - if all rules involved in a cycle are ... TODO
*)

(* Pre-compute some properties of the grammar *)
type 'g analysis = {
  g: 'g grammar;
  (* Productions to consider *)
  valid_prod: 'g production Boolvector.t;
  (* Non-terminals deriving a non-empty string *)
  nonnull_nt: 'g nonterminal Boolvector.t;
  (* Productions deriving a non-empty string *)
  nonnull_prod: 'g production Boolvector.t;
}

let analyze g =
  (* A production is valid if it has no `error` symbol *)
  let valid_prod = Boolvector.init (Production.cardinal g) begin fun prod ->
      Array.for_all (fun sym ->
          match Symbol.desc g sym with
          | T t -> Terminal.kind g t <> `ERROR
          | _ -> true
        ) (Production.rhs g prod)
    end
  in
  (* Pre-compute productions in which a non-terminal occurs *)
  let nt_occurrences = Vector.make (Nonterminal.cardinal g) IndexSet.empty in
  Index.rev_iter (Production.cardinal g) begin fun prod ->
    if valid_prod.?(prod) then
      Array.iter begin fun sym ->
        match Symbol.desc g sym with
        | T _ -> ()
        | N nt -> nt_occurrences.@(nt) <- IndexSet.add prod
      end (Production.rhs g prod)
  end;
  (* Determine nt and prod that can derive a non-empty string *)
  let nonnull_nt = Boolvector.make (Nonterminal.cardinal g) false in
  let nonnull_prod = Boolvector.make (Production.cardinal g) false in
  let rec set_prod prod =
    if not nonnull_prod.?(prod) then (
      Boolvector.set nonnull_prod prod;
      set_nt (Production.lhs g prod)
    )
  and set_nt nt =
    if not nonnull_nt.?(nt) then (
      Boolvector.set nonnull_nt nt;
      IndexSet.iter set_prod nt_occurrences.:(nt)
    )
  in
  Index.iter (Production.cardinal g) begin fun prod ->
    if
      Array.exists (fun sym ->
        match Symbol.desc g sym with
        | N _ -> false
        | T t -> match Terminal.kind g t with
          | `REGULAR -> true
          | `EOF -> false
          | `ERROR | `PSEUDO -> false
      ) (Production.rhs g prod)
    then set_prod prod
  end;
  {g; valid_prod; nonnull_nt; nonnull_prod}

(* Documents for constructing indented output *)
module Doc = struct
  type document =
    | Text of string
    | Indent of (int * document)
    | Join of document * document

  let empty = Text ""

  let text x = Text x

  let join x y =
    match x, y with
    | Text "", v | v, Text "" -> v
    | _ -> Join (x, y)

  let list = function
    | [] -> empty
    | [x] -> x
    | x :: xs -> List.fold_left join x xs

  let list_map f docs = list (List.map f docs)

  let indent n = function
    | Text "" -> Text ""
    | Indent (m, doc) -> Indent (n + m, doc)
    | doc -> Indent (n, doc)

  let wrap a b c = join a (join c b)

  let rec concat sep f ?(first=f) = function
    | [] -> empty
    | [x] -> first x
    | x :: xs -> join (first x) (join sep (concat sep f xs))

  let padding = String.make 80 ' '

  let rec render_text nl o n pos text =
    match String.index_from_opt text pos '\n' with
    | None ->
      let len = String.length text - pos in
      if len > 0 then (
        if !nl then (
          o padding 0 (Int.min 80 n);
          nl := false;
        );
        o text pos len
      );
    | Some pos' ->
      if pos' > pos && !nl then (
        o padding 0 (Int.min 80 n);
        nl := false;
      );
      let pos' = pos' + 1 in
      o text pos (pos' - pos);
      nl := true;
      render_text nl o n pos' text

  let rec render nl o n = function
    | Text text -> render_text nl o n 0 text
    | Indent (d, doc) -> render nl o (n + d) doc
    | Join (a, b) ->
      render nl o n a;
      render nl o n b

  let render o n doc = render (ref false) o n doc
end

(* How do we represent conflicts?

   If some state present a conflict, we start by building a map of preserved
   actions by lookahead symbol.
*)


module Conflict = struct

  type 'g actions = {
    shift: 'g item indexset;
    reduce: 'g item indexset;
  }

  let get_actions map t =
    match IndexMap.find_opt t map with
    | Some a -> a
    | None -> {shift = IndexSet.empty; reduce = IndexSet.empty}

  let items_for_shifting g source term =
    Lr1.items g source |> IndexSet.filter (fun it ->
        let prod, pos = Item.desc g it in
        let rhs = Production.rhs g prod in
        pos < Array.length rhs &&
        match Symbol.desc g rhs.(pos) with
        | T term' -> Index.equal term term'
        | N nt -> IndexSet.mem term (Nonterminal.first g nt)
      )

  let add_shift g tr map =
    match Symbol.desc g (Transition.symbol g tr) with
    | N _ -> map
    | T term ->
      let items = items_for_shifting g (Transition.source g tr) term in
      let actions = get_actions map term in
      assert (IndexSet.is_empty actions.shift);
      IndexMap.add term {actions with shift = items} map

  let item_for_reducing g prod =
    Item.make g prod (Production.length g prod - 1)

  let add_reduction g red map =
    let item = item_for_reducing g (Reduction.production g red) in
    IndexSet.fold begin fun term map ->
      let actions = get_actions map term in
      let reduce = IndexSet.add item actions.reduce in
      IndexMap.add term {actions with reduce = reduce} map
    end (Reduction.lookaheads g red) map

  let remove_reduce g map (term, prod) =
    let actions = get_actions map term in
    let reduce = IndexSet.remove (item_for_reducing g prod) actions.reduce in
    assert (reduce != actions.reduce);
    IndexMap.add term {actions with reduce} map

  type relation =
    | Shift_over_reduce
    | Reduce_over_shift
    | Reduce_reduce

  type 'g edge = {
    source: 'g item index;
    target: 'g item index;
    relation: relation;
  }

  let register_removed_shift g map register source (term, _) =
    let actions = get_actions map term in
    assert (IndexSet.is_empty actions.shift);
    IndexSet.iter begin fun source ->
      IndexSet.iter begin fun target ->
        register {source; target; relation = Reduce_over_shift}
      end actions.reduce
    end (items_for_shifting g source term)

  let register_removed_reduce g map register (term, prods) =
    let actions = get_actions map term in
    List.iter begin fun prod ->
      let source = item_for_reducing g prod in
      IndexSet.iter begin fun target ->
        register {source; target; relation = Shift_over_reduce}
      end actions.shift;
      IndexSet.iter begin fun target ->
        register {source; target; relation = Reduce_reduce}
      end actions.reduce
    end prods

  let process_lr1 g register lr1 =
    match
      Conflicts.silent_transition_conflicts g lr1,
      Conflicts.silent_reduction_conflicts g lr1
    with
    | [], [] -> ()
    | removed_shift, removed_reduce ->
      let actions =
        IndexMap.empty
        |> IndexSet.fold (add_shift g) (Transition.successors g lr1)
        |> IndexSet.fold (add_reduction g) (Reduction.from_lr1 g lr1)
      in
      (* Remove extra ones *)
      let actions =
        List.fold_left (remove_reduce g)
          actions (Conflicts.extra_reductions g lr1)
      in
      (* Register conflicts *)
      List.iter
        (register_removed_shift g actions register lr1)
        removed_shift;
      List.iter
        (register_removed_reduce g actions register)
        removed_reduce

  type associativity =
    | Left
    | Right
    | Prec
    | Invalid

  let dump_scc (type g) path (g : g grammar) successors bridges =
    let oc = lazy (
      let oc = open_out_bin path in
      output_string oc "digraph G {\n";
      output_string oc "  rankdir=LR;\n";
      output_string oc "  node[shape=rect];\n";
      oc
    ) in
    let (module SCC) =
      Tarjan.indexed_scc (Item.cardinal g)
        ~succ:(fun f i ->
            successors i (fun edge -> f edge.target);
            bridges i (fun (_b,target) -> f target)
          )
    in
    let p fmt = Printf.kfprintf (fun oc -> output_char oc '\n') (Lazy.force oc) fmt in
    Vector.iteri begin fun scc nodes ->
      let self_sr = ref false in
      let self_rs = ref false in
      let self_rr = ref false in
      IndexSet.iter begin fun node ->
        successors node begin fun edge ->
          let scc' = SCC.component.:(edge.target) in
          if Index.equal scc scc' then (
            match edge.relation with
            | Shift_over_reduce -> self_sr := true
            | Reduce_over_shift -> self_rs := true
            | Reduce_reduce     -> self_rr := true
          )
        end
      end nodes;
      match !self_sr, !self_rs, !self_rr with
      | false, false, false -> ()
      | true , false, false -> ()
      | false, true , false -> ()
      | _ ->
        IndexSet.iter begin fun node ->
          p "  p%d[label=%S];" (Index.to_int node) (Item.to_string g node);
          successors node begin fun edge ->
            let scc' = SCC.component.:(edge.target) in
            if Index.equal scc scc' then (
              p "  p%d -> p%d[label=%S];" (Index.to_int edge.source) (Index.to_int edge.target)
                (match edge.relation with
                 | Shift_over_reduce -> "R"
                 | Reduce_over_shift -> "L"
                 | Reduce_reduce -> "LR")
            )
          end;
          bridges node begin fun (bridge,_target) ->
            p "  p%d -> b%d [dir=both];\n" (Index.to_int node) (Index.to_int bridge);
          end
        end nodes;
        prerr_endline "cyclic precedences"
    end SCC.nodes;
    if Lazy.is_val oc then (
      p "}";
      close_out (Lazy.force oc)
    )

  let solve (type g) (g : g grammar) =
    let items = Item.cardinal g in
    (* Collect all conflicts by item *)
    let successors = Vector.make items [] in
    let predecessors = Vector.make items [] in
    (* Lift representation to bridge base *)
    let Bridge_maker.T maker = Bridge_maker.make items in
    (* Initialize arrays *)
    let register edge =
      successors.@(edge.source) <- List.cons edge;
      predecessors.@(edge.target) <- List.cons edge;
      match edge.relation with
      | Shift_over_reduce ->
        Bridge_maker.link_right maker edge.source edge.target
      | Reduce_over_shift ->
        Bridge_maker.link_left maker edge.source edge.target
      | Reduce_reduce ->
        Bridge_maker.link_right maker edge.source edge.target;
        Bridge_maker.link_left maker edge.source edge.target
    in
    Index.iter (Lr1.cardinal g) (process_lr1 g register);
    if false then dump_scc "raw.dot" g begin fun node f ->
      List.iter f successors.:(node)
    end begin fun _ _ -> () end;
    (* Represent merging candidates as bridges *)
    let item_bridges = Vector.make items [] in
    let _ = Index.fold items None begin fun acc item ->
        if List.is_empty successors.:(item) &&
           List.is_empty predecessors.:(item) then
          (* Skip unused items *)
          acc
        else (
          begin match acc with
            | Some item'
              when Index.equal (Item.production g item) (Item.production g item') ->
              (* Item from same production: new bridge! *)
              let b = Bridge_maker.bridge maker item' item in
              (*Printf.eprintf "bridge %s <->\n       %s\n" (Item.to_string g item) (Item.to_string g item');*)
              item_bridges.@(item) <- List.cons (b, item');
              item_bridges.@(item') <- List.cons (b, item)
            | _ -> ()
          end;
          Some item
        )
      end
    in
    let bridge_count, pb = Bridge_maker.create_problem maker in
    let burned = Bridge_burner.solve pb in
    Printf.eprintf "Bridges burned: %d/%d\n"
      (IndexSet.cardinal burned) (cardinal bridge_count);
    (* Generate SCC of the graph induced by conflicts *)
    let (module SCC) =
      Tarjan.indexed_scc items
        ~succ:(fun f i ->
            List.iter (fun edge -> f edge.target) successors.:(i);
            List.iter (fun (bridge,target) ->
                if not (IndexSet.mem bridge burned) then
                  f target
              ) item_bridges.:(i)
          )
    in
    if false then dump_scc "conflicts.dot" g
      (fun i f -> List.iter f successors.:(i))
      (fun i f -> List.iter (fun (b,_ as arg) -> if not (IndexSet.mem b burned) then f arg) item_bridges.:(i));
    (* Associativity is enforced in non-trivial components *)
    let it_ranks = Vector.make items 0 in
    let it_assoc = Vector.make items Prec in
    Vector.iteri begin fun scc nodes ->
        let self_l = ref false in
        let self_r = ref false in
        let pred_n = ref (-1) in
        let pred_l = ref false in
        let pred_r = ref false in
        IndexSet.iter begin fun node ->
          List.iter begin fun {source; relation; _} ->
            let scc' = SCC.component.:(source) in
            if Index.equal scc scc' then
              match relation with
              | Shift_over_reduce -> self_r := true
              | Reduce_over_shift -> self_l := true
              | Reduce_reduce ->
                prerr_endline "tree-sitter gen: broken invariant: reduce-reduce conflict in a single component";
                self_l := true;
                self_r := true;
            else (
              let rank = it_ranks.:(source) in
              if rank > !pred_n then
                (pred_n := rank; pred_l := false; pred_r := false);
              if rank = !pred_n then (
                begin match relation with
                  | Shift_over_reduce -> pred_r := true
                  | Reduce_over_shift -> pred_l := true
                  | Reduce_reduce -> pred_l := true; pred_r := true
                end;
                begin match it_assoc.:(source) with
                  | Left -> pred_l := true;
                  | Right -> pred_r := true;
                  | Prec | Invalid -> pred_l := true; pred_r := true
                end;
              )
            )
          end predecessors.:(node)
        end nodes;
        let assoc =
          if !self_l && !self_r then (
            prerr_endline "tree-sitter gen: broken invariant: cyclic precedence";
            Invalid
          ) else if !self_l then
            Left
          else if !self_r then
            Right
          else if !pred_l && !pred_r then
            Prec
          else if !pred_l then
            Left
          else if !pred_r then
            Right
          else
            Prec
        in
        let rank =
          if (!self_l && !self_r) || (!pred_l && !pred_r) then
            !pred_n + 1
          else if (!self_l && !pred_l) || (!self_r && !pred_r) then
            !pred_n
          else
            !pred_n + 1
        in
        IndexSet.iter (fun it ->
            it_assoc.:(it) <- assoc;
            it_ranks.:(it) <- rank;
          ) nodes;
    end SCC.nodes;
    (* Clear unused items by setting rank to -1 *)
    Index.iter items begin fun it ->
      if List.is_empty predecessors.:(it) &&
         List.is_empty successors.:(it) then
        it_ranks.:(it) <- (-1);
    end;
    (it_ranks, it_assoc)
end

module Converter = struct
  let (!!) = Doc.text
  let (^^) = Doc.join

  let bind_rule lhs rhs =
    !!lhs ^^ !!": $ => " ^^ rhs ^^ !!",\n"

  let mangled g nt =
    Symbol.to_string ~mangled:true g (Symbol.inj_n g nt)

  let import_terminal g term =
    match Terminal.kind g term with
    | `EOF -> "token(\"EOF\")"
    | _ ->
      let rhs = Option.value (Terminal.alias g term)
          ~default:(Terminal.to_string g term)
      in
      if rhs = "" || rhs.[0] <> '"'
      then Printf.sprintf "token(%S)" rhs
      else Printf.sprintf "token(%s)" rhs

  let import_raw_producer g prod =
    match Symbol.desc g prod with
    | T t -> !!(import_terminal g t)
    | N nt -> !!"$." ^^ !!(mangled g nt)

  let import_producer not_optional g prod =
    match Symbol.desc g prod with
    | T t -> !!(import_terminal g t)
    | N n ->
      let doc = !!"$." ^^ !!(mangled g n) in
      if Nonterminal.nullable g n && not not_optional
      then Doc.wrap !!"optional(" !!")" doc
      else doc

  let symbol_nonnull ga sym =
    match Symbol.desc ga.g sym with
    | T t -> Terminal.kind ga.g t = `REGULAR
    | N n -> ga.nonnull_nt.?(n)

  let symbol_nullable g sym =
    match Symbol.desc g sym with
    | T _ -> false
    | N n -> Nonterminal.nullable g n

  let import_production ga ranks assocs prod =
    assert ga.nonnull_prod.?(prod);
    let rhs = (Production.rhs ga.g prod) in
    let not_optional = ref (Array.for_all (symbol_nullable ga.g) rhs) in
    let tail = ref [] in
    let last_rank = ref (-1, Conflict.Invalid) in
    let flush_tail () =
      match !tail with
      | [] -> !!"seq()"
      | [x] -> x
      | xs -> Doc.wrap !!"seq(" !!")" (Doc.concat !!"," Fun.id xs)
    in
    let flush_rank () =
      match !tail, !last_rank with
      | [], _ | _, (-1, _) -> ()
      | _, (level, assoc) ->
        let assoc = match assoc with
          | Left -> "prec.left"
          | Right -> "prec.right"
          | Invalid -> "prec.invalid"
          | Prec -> "prec"
        in
        tail := [Doc.wrap !!(Printf.sprintf "%s(%d," assoc level) !!")" (flush_tail ())]
    in
    let add_sym rank sym =
      if fst rank > (-1) && rank <> !last_rank then flush_rank ();
      if symbol_nonnull ga sym then (
        tail := import_producer !not_optional ga.g sym :: !tail;
        not_optional := false
      );
      if fst rank > (-1) then
        last_rank := rank
    in
    for pos = Array.length rhs - 1 downto 0 do
      let item = Item.make ga.g prod pos in
      add_sym (ranks.:(item), assocs.:(item)) rhs.(pos)
    done;
    if !last_rank <> (0, Prec) then
      flush_rank ();
    flush_tail ()

  let import_nonterminals ga ranks assocs =
    (* Pre-compute productions defining a non-terminal *)
    let nt_prods = Vector.make (Nonterminal.cardinal ga.g) IndexSet.empty in
    let entrypoint = ref None in
    Index.rev_iter (Production.cardinal ga.g) begin fun prod ->
      if ga.valid_prod.?(prod) && ga.nonnull_prod.?(prod) then
        match Production.kind ga.g prod with
        | `REGULAR ->
          nt_prods.@(Production.lhs ga.g prod) <- IndexSet.add prod
        | `START ->
          if Option.is_none !entrypoint then
            let n = match Symbol.desc ga.g (Production.rhs ga.g prod).(0) with
              | Symbol.T _ -> assert false
              | Symbol.N n -> n
            in
            entrypoint := Some n
    end;
    let rules =
      (* Output all productions of a non-terminal *)
      Vector.to_seqi nt_prods |>
      Seq.filter_map begin fun (nt, prods) ->
        if IndexSet.is_empty prods then None else Some begin
            let rhs =
              if IndexSet.is_singleton prods then
                import_production ga ranks assocs (IndexSet.choose prods)

              else
                Doc.wrap !!"choice(\n" !!"\n)"
                  (Doc.indent 2 (Doc.concat !!",\n"
                                   (import_production ga ranks assocs)
                                   (IndexSet.elements prods)))
            in
            (nt, rhs)
          end
      end
    in
    (Option.get !entrypoint, rules)

  let convert_syntax ga ranks assocs basename =
    let entrypoint, rules = import_nonterminals ga ranks assocs in
    (*let entrypoint =
      if List.exists (fun (nt, _) -> mangled ga.g nt = "start") rules then
        "start"
      else
        List.find_map (fun (nt, _) ->
            if Nonterminal.kind ga.g nt = `START
            then Some (mangled ga.g nt)
            else None
          ) rules
        |> Option.get
      in*)
    Doc.list [
      !!"export default {\n";
      Doc.indent 2 @@ Doc.list [
        !!"name: '"; !!basename; !!"',\n";
        !!"rules: {\n";
        Doc.indent 2 @@ Doc.list [
          bind_rule "start" !!("$." ^ mangled ga.g entrypoint);
          Doc.list_map
            (fun (lhs, rhs) -> bind_rule (mangled ga.g lhs) rhs)
            (List.of_seq rules);
          (*Doc.list (List.filter_map import_token symbols);*)
        ];
        !!"}\n";
      ];
      !! "};\n";
    ]
end

let import g basename =
  let ga = analyze g in
  let ranks, assocs = Conflict.solve g in
  let doc = Converter.convert_syntax ga ranks assocs basename in
  Doc.render (output_substring stdout) 0 doc
